const catchAsync = require('../utils/catchAsync');
const { successResponse, paginatedResponse } = require('../utils/response');
const { questionService } = require('../services');

const createQuestion = catchAsync(async (req, res) => {
  const question = await questionService.createQuestion(req.body);
  successResponse(res, { question }, 'Question created.', 201);
});

const listQuestions = catchAsync(async (req, res) => {
  const { questions, total, page, limit } = await questionService.listQuestions(req.query);
  paginatedResponse(res, questions, page, limit, total);
});

const getQuestion = catchAsync(async (req, res) => {
  const question = await questionService.getQuestionById(req.params.questionId);
  successResponse(res, { question });
});

const generateQuestion = catchAsync(async (req, res) => {
  const { topic, difficulty, type } = req.body;
  const question = await questionService.generateAndSaveQuestion(topic, difficulty, type);
  successResponse(res, { question }, 'Question generated by AI.', 201);
});

const seedQuestions = catchAsync(async (req, res) => {
  const result = await questionService.seedQuestions();
  successResponse(res, result, result.seeded ? 'Questions seeded.' : 'Questions already exist.');
});

module.exports = {
  createQuestion,
  listQuestions,
  getQuestion,
  generateQuestion,
  seedQuestions,
};
